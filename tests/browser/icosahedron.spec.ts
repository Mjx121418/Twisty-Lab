import { expect, test } from '@playwright/test';
import { expectViews, setViews } from './view-controls';

test('110-piece icosahedron synchronizes conical and spherical jumbling, controls, blocking and saves', async ({ page }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('./');
  await expect(page.getByTestId('state-digest')).toHaveText(/^[0-9a-f]{64}$/);
  await page.getByLabel('Animation speed').selectOption('0');
  await page.getByLabel('Puzzle', { exact: true }).selectOption('icosahedron-110');
  await expectViews(page, ['cube', 'sphere']);
  const euclidean = page.locator('[data-view-id="cube"]'), sphere = page.locator('[data-view-id="sphere"]');
  await expect(euclidean).toHaveAttribute('data-realization-id', 'icosahedron-110-euclidean-v1');
  await expect(sphere).toHaveAttribute('data-realization-id', 'icosahedron-110-spherical-v1');
  await expect(euclidean.getByLabel('Euclidean puzzle')).toBeVisible();
  await expect(sphere.getByLabel('Spherical puzzle')).toBeVisible();
  await expect(page.locator('.metrics').getByText('110', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/icosahedron-110-solved.png', fullPage: true });
  const initial = await page.getByTestId('state-digest').textContent();
  await page.getByRole('button', { name: 'Select center/A', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Twist family controller' })).toHaveAttribute('data-matching-families', 'A');
  const jump = page.getByRole('button', { name: /^A destination 1(?:,|$)/ });
  await expect(jump).toHaveAttribute('data-status', 'Planned');
  await jump.click();
  await expect(page.getByTestId('app')).toHaveAttribute('data-animating', 'false');
  await expect(page.getByTestId('state-digest')).not.toHaveText(initial!);
  const first = await page.getByTestId('state-digest').textContent();
  await page.keyboard.press('Escape');
  await page.getByText('Advanced movement list', { exact: true }).click();
  await page.getByRole('button', { name: 'Move I', exact: true }).click();
  await expect(page.getByTestId('blocking-evidence')).toBeVisible();
  await expect(page.getByTestId('state-digest')).toHaveText(first!);
  await page.getByRole('button', { name: 'Move O_j', exact: true }).click();
  await expect(page.getByTestId('state-digest')).not.toHaveText(first!);
  await expect(page.getByTestId('app')).toHaveAttribute('data-animating', 'false');
  const jumbled = await page.getByTestId('state-digest').textContent();
  for (const view of [euclidean, sphere]) await expect(view).toHaveAttribute('data-state-digest', jumbled!);
  await page.screenshot({ path: 'test-results/icosahedron-110-jumbled.png', fullPage: true });
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save session ↗' }).click();
  const saved = await download;
  await page.getByRole('button', { name: 'Reset puzzle', exact: true }).click();
  await expect(page.getByTestId('state-digest')).toHaveText(initial!);
  await page.getByLabel('Open session file').setInputFiles((await saved.path())!);
  await expect(page.getByTestId('state-digest')).toHaveText(jumbled!);
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await expect(page.getByTestId('state-digest')).toHaveText(first!);
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await expect(page.getByTestId('state-digest')).toHaveText(initial!);
  await setViews(page, ['sphere']);
  await expect(page.locator('.views canvas')).toHaveCount(1);
  await setViews(page, ['cube', 'sphere']);
  await expect(page.getByRole('alert')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('152-piece icosahedron uses relative spherical turns with planar and spherical models', async ({ page }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('./');
  await expect(page.getByTestId('state-digest')).toHaveText(/^[0-9a-f]{64}$/);
  await page.getByLabel('Animation speed').selectOption('0');
  await page.getByLabel('Puzzle', { exact: true }).selectOption('icosahedron-152');
  await expectViews(page, ['cube', 'sphere']);
  await expect(page.locator('.metrics').getByText('152', { exact: true })).toBeVisible();
  await expect(page.locator('[data-view-id="cube"]')).toHaveAttribute('data-realization-id', 'icosahedron-152-euclidean-v1');
  await expect(page.locator('[data-view-id="sphere"]')).toHaveAttribute('data-realization-id', 'icosahedron-152-spherical-v1');
  const initial = await page.getByTestId('state-digest').textContent();
  const ring = page.getByRole('group', { name: 'A angular stops', exact: true });
  await expect(ring.locator('button[data-stop]')).toHaveCount(15);
  await expect(ring.getByRole('button', { name: 'A current position, 0.000 degrees', exact: true })).toHaveAttribute('aria-current', 'step');
  // Commands outside the circle use the same recorded current position.
  await page.getByLabel('Algorithm', { exact: true }).fill('A');
  await page.getByRole('button', { name: 'Play algorithm →', exact: true }).click();
  await expect(ring).toHaveAttribute('data-current-angle', '120.000');
  await expect(ring.locator('[aria-current="step"]')).toHaveAccessibleName('A current position, 120.000 degrees');
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await expect(ring).toHaveAttribute('data-current-angle', '0.000');
  await expect(page.getByTestId('state-digest')).toHaveText(initial!);
  const jump = page.getByRole('button', { name: 'A turn +44.478 degrees', exact: true });
  await expect(jump).toHaveAttribute('data-status', 'Legal');
  const nextStop = ring.getByRole('button', { name: 'A turn +75.522 degrees', exact: true });
  await expect(nextStop).toHaveAttribute('data-status', 'Legal');
  await expect(ring.locator('button[data-status="Pending"]')).toHaveCount(0);
  await jump.hover();
  await expect(ring.getByTestId('relative-turn-arc')).toHaveAttribute('d', /^M 160 40 A 120 120 0 0 1 /);
  await jump.focus();
  await jump.press('ArrowRight');
  await expect(nextStop).toBeFocused();
  await nextStop.press('ArrowLeft');
  await expect(jump).toBeFocused();
  await expect(page.getByTestId('state-digest')).toHaveText(initial!);
  await page.screenshot({ path: 'test-results/icosahedron-152-solved.png', fullPage: true });
  await jump.click();
  await expect(page.getByTestId('app')).toHaveAttribute('data-animating', 'false');
  await expect(page.getByTestId('state-digest')).not.toHaveText(initial!);
  const first = await page.getByTestId('state-digest').textContent();
  await expect(ring).toHaveAttribute('data-current-angle', '44.478');
  await expect(ring.locator('[aria-current="step"]')).toHaveAccessibleName('A current position, 44.478 degrees');
  expect(Number(await ring.locator('[aria-current="step"]').getAttribute('data-angle'))).toBeCloseTo(44.47751218593*Math.PI/180,7);
  const inverse = ring.getByRole('button', { name: 'A turn -44.478 degrees', exact: true });
  await inverse.hover();
  await expect(ring.getByTestId('relative-turn-arc')).not.toHaveAttribute('d', /^M 160 40 /);
  await ring.screenshot({ path: 'test-results/icosahedron-152-current-angle.png' });
  await page.getByLabel('Twist family', { exact: true }).selectOption('I');
  const blocked = page.getByRole('button', { name: 'I turn +120.000 degrees', exact: true });
  await expect(blocked).toHaveAttribute('data-status', 'Blocked');
  await expect(blocked).toHaveClass(/blocked-stop/);
  await blocked.click();
  await expect(page.getByTestId('blocking-evidence')).toBeVisible();
  await expect(page.getByTestId('state-digest')).toHaveText(first!);
  // Plane crossing alone is insufficient evidence. The planar realization
  // has a collision during D's path, while the selected spherical rules allow it.
  await page.getByLabel('Twist family', { exact: true }).selectOption('D');
  const ordinary = page.getByRole('button', { name: 'D turn +120.000 degrees', exact: true });
  await expect(ordinary).toHaveAttribute('data-status', 'Legal');
  await ordinary.click();
  await expect(page.getByTestId('state-digest')).not.toHaveText(first!);
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await expect(page.getByTestId('state-digest')).toHaveText(first!);
  await page.getByLabel('Twist family', { exact: true }).selectOption('O');
  const handoff = page.getByRole('button', { name: 'O turn +44.478 degrees', exact: true });
  await expect(handoff).toHaveAttribute('data-status', 'Legal');
  await handoff.click();
  await expect(page.getByTestId('app')).toHaveAttribute('data-animating', 'false');
  await expect(page.getByRole('group', { name: 'O angular stops', exact: true })).toHaveAttribute('data-current-angle', '44.478');
  await page.getByLabel('Twist family', { exact: true }).selectOption('A');
  await expect(ring).toHaveAttribute('data-current-angle', '44.478');
  const jumbled = await page.getByTestId('state-digest').textContent();
  expect(jumbled).not.toBe(first);
  for (const view of ['cube','sphere']) await expect(page.locator(`[data-view-id="${view}"]`)).toHaveAttribute('data-state-digest', jumbled!);
  await page.screenshot({ path: 'test-results/icosahedron-152-jumbled.png', fullPage: true });
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save session ↗' }).click();
  const saved = await download;
  await page.getByRole('button', { name: 'Reset puzzle', exact: true }).click();
  await expect(page.getByTestId('state-digest')).toHaveText(initial!);
  await expect(ring).toHaveAttribute('data-current-angle', '0.000');
  await page.getByLabel('Open session file').setInputFiles((await saved.path())!);
  await expect(page.getByTestId('state-digest')).toHaveText(jumbled!);
  await expect(ring).toHaveAttribute('data-current-angle', '44.478');
  await page.getByLabel('Twist family', { exact: true }).selectOption('O');
  const otherRing = page.getByRole('group', { name: 'O angular stops', exact: true });
  await expect(otherRing).toHaveAttribute('data-current-angle', '44.478');
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await expect(otherRing).toHaveAttribute('data-current-angle', '0.000');
  await page.getByLabel('Twist family', { exact: true }).selectOption('A');
  await expect(ring).toHaveAttribute('data-current-angle', '44.478');
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await expect(page.getByTestId('state-digest')).toHaveText(initial!);
  await expect(ring).toHaveAttribute('data-current-angle', '0.000');
  await page.getByRole('button', { name: '↷ Redo', exact: true }).click();
  await expect(ring).toHaveAttribute('data-current-angle', '44.478');
  await page.getByRole('button', { name: '↷ Redo', exact: true }).click();
  await page.getByLabel('Twist family', { exact: true }).selectOption('O');
  await expect(otherRing).toHaveAttribute('data-current-angle', '44.478');
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await page.getByLabel('Twist family', { exact: true }).selectOption('A');
  await expect(ring).toHaveAttribute('data-current-angle', '0.000');
  await page.getByRole('button', { name: 'Select face/A-C-K-Q', exact: true }).click();
  const controls = page.getByRole('region', { name: 'Relative twist controller' });
  await expect(controls.getByRole('status')).toHaveText(/available axes include this selection/);
  await expect(controls).toHaveAttribute('data-matching-families', /A/);
  await controls.getByRole('button', { name: 'Clear piece selection' }).click();
  await setViews(page, ['sphere']);
  await expect(page.locator('.views canvas')).toHaveCount(1);
  await setViews(page, ['cube','sphere']);
  await expect(page.getByRole('alert')).toHaveCount(0);
  expect(errors).toEqual([]);
});
